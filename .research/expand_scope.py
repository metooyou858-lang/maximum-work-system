from pathlib import Path
from docx import Document
import hashlib
import json

root = Path.cwd()
scope = ('Система предназначена для учёта работ компании MAXIMUM: алмазного сверления и бурения, '
         'резки бетона и кирпича, изготовления и усиления проёмов, демонтажа, штробления, '
         'сопутствующих ремонтно-строительных работ и отбора кернов. '
         'Компания также производит, продаёт и восстанавливает алмазные коронки. '
         'Первая версия объединяет сотрудников, объекты, оборудование, отметки времени и персональные отчёты; '
         'отдельная автоматизация производства, продаж и финансов относится к последующим согласованиям.')
report = ('Структурированный отчёт: объект, дата, вид работ, соответствующие ему параметры, '
          'количество или объём с единицей измерения, время и причина отклонения от нормы. '
          'Для бурения указываются параметры отверстий; для резки, проёмов, демонтажа и других работ — '
          'показатели по утверждённой форме заказчика.')
changed = []
clips = {str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in root.rglob('clip *.docx')}
for p in sorted(root.rglob('*.docx')):
    if p.name.startswith(('clip', '~$')) or 'расширенное описание' in p.name: continue
    d = Document(p)
    def set_text(q, text):
        if q.runs:
            q.runs[0].text = text
            for r in q.runs[1:]: r.text = ''
        else: q.add_run(text)
    set_text(d.paragraphs[0], 'Протокол совещания по системе учёта работ сотрудников и оборудования')
    if scope not in [q.text for q in d.paragraphs]:
        d.paragraphs[3].insert_paragraph_before(scope)
    for table in d.tables:
        for row in table.rows:
            for cell in row.cells:
                for q in cell.paragraphs:
                    if q.text.startswith('Структурированный отчет:'):
                        set_text(q, report)
    try:
        d.save(p)
    except PermissionError:
        p=p.with_name(p.stem+' расширенное описание.docx')
        d.save(p)
    check=Document(p)
    assert scope in [q.text for q in check.paragraphs]
    assert not any('учета буровых работ' in q.text for q in check.paragraphs)
    changed.append(str(p.relative_to(root)))

for name in ['Описание проекта.md','Решения после совещания 26.09.2026.md','AGENTS.md','Диалог.md','Сайт заказчика и сопоставление обсуждений.md']:
    p=root/name
    s=p.read_text(encoding='utf-8')
    if name=='Описание проекта.md':
        s=s.replace('# Учёт буровых работ — описание MVP','# Учёт работ, сотрудников и оборудования — описание MVP')
        s=s.replace('Предлагаем создать систему',scope+'\n\nПредлагаем создать систему',1)
        s=s.replace('с двумя основными разделами','с тремя основными разделами')
        s=s.replace('по форме заказчика и фиксирует','по форме заказчика с указанием вида работ, его параметров и выполненного количества или объёма в соответствующих единицах, затем фиксирует')
    elif name=='Решения после совещания 26.09.2026.md':
        s=s.replace('## Первая рабочая версия','## Предметная область — уточнение от 28 сентября 2026 года\n\n'+scope+'\n\nОтчётность описывает разные виды работ; поля и единицы измерения определяются формой заказчика для соответствующего вида работы.\n\n## Первая рабочая версия',1)
    elif name=='AGENTS.md':
        s=s.replace('- Рабочее название: «Учёт буровых работ». Официальное название пока не выбрано.', '- В документах использовать широкое описание «Учёт работ, сотрудников и оборудования». Официальное название пока не выбрано; название папки «Учёт буровых работ» историческое.\n- Уточнение пользователя от 28.09.2026: во всех актуальных документах описывать весь профиль работ MAXIMUM — алмазное сверление и бурение, резку, изготовление и усиление проёмов, демонтаж, штробление, сопутствующие ремонтно-строительные работы и отбор кернов. Не сводить деятельность к бурению образцов. Коронки компания также производит, продаёт и восстанавливает; отдельные модули производства и продаж не добавляются в первую версию автоматически.\n- Отчёты должны описываться через вид работ, соответствующие параметры и единицы измерения, а не только через отверстия. Исходные реплики в «Диалог.md» и clip 1–5 сохраняются как история; актуальное уточнение помещено перед диалогом.')
    elif name=='Диалог.md':
        first,rest=s.split('\n',1)
        s=first+'\n\n> Актуальное уточнение от 28.09.2026. '+scope+' Исходные реплики ниже сохранены дословно и отражают этап обсуждения, а не полное актуальное описание деятельности.\n'+rest
    else:
        s=s.replace('Первое описание «бурение образцов бетона» передавало только часть бизнеса.', 'По уточнению владельца проекта от 28.09.2026 во всех актуальных документах принято широкое описание: учёт работ, сотрудников и оборудования компании MAXIMUM.')
        s=s.replace('Расширять первую версию до всех направлений компании без отдельного решения не следует.', 'Виды работ описываются в пределах общего оперативного учёта; отдельные модули производства, продаж и финансов требуют своего согласования.')
        s=s.replace('Рабочее название сохраняется, но описание предметной области должно быть шире отбора образцов', 'В актуальных документах используется широкое описание «Учёт работ, сотрудников и оборудования»; официальный бренд приложения ещё не выбран')
        s=s.replace('В «Описание проекта.md» написано «с двумя основными разделами», хотя далее перечислены сотрудники, объекты и оборудование. Это редакционная несогласованность: по последним решениям основных сущностей три. Исходные документы при исследовании не переписаны.', 'После уточнения владельца проекта от 28.09.2026 описание деятельности расширено в проектных документах и пяти версиях Word-протокола. В «Описание проекта.md» также исправлено количество основных разделов: сотрудники, объекты и оборудование — три раздела. Исходные реплики диалога и расшифровки сохранены как история обсуждения.')
        s=s.replace('Только бурение и керны или также резка, проёмы и другие направления', 'Какие из направлений компании первыми проверяем на реальных сменах; какие формы и единицы измерения нужны для каждого')
    p.write_text(s,encoding='utf-8')
    changed.append(name)
assert all(hashlib.sha256(Path(p).read_bytes()).hexdigest()==h for p,h in clips.items())
(root/'.research'/'scope-edit-result.json').write_text(json.dumps(changed,ensure_ascii=False,indent=2),encoding='utf-8')
print('Updated:',len(changed),'files. Original transcripts preserved.')
