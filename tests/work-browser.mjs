import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { createWorkApp } from '../work-server.mjs';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(process.argv[2] || join(root, 'package.json'));
const { chromium } = require('playwright');
const out = join(root, 'artifacts', 'qa');
mkdirSync(out, { recursive: true });
const app = createWorkApp({ database: ':memory:', bootstrapAdmin: { login: 'manager.maximum', password: 'correct-horse-battery-2026' } });
const listen = server => new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const fit = page => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth);
let browser;

try {
  await listen(app.server);
  const origin = `http://127.0.0.1:${app.server.address().port}`;
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(origin);
  await page.getByRole('heading', { name: 'Рабочий кабинет', exact: true }).waitFor();
  assert.equal(await fit(page), true, 'Горизонтальная прокрутка на экране входа');
  await page.getByLabel('Логин', { exact: true }).fill('manager.maximum');
  await page.getByLabel('Пароль', { exact: true }).fill('correct-horse-battery-2026');
  await page.getByRole('button', { name: 'Войти', exact: true }).click();
  await page.getByRole('heading', { name: 'Мои объекты', exact: true }).waitFor();
  await page.screenshot({ path: join(out, 'work-01-empty-390.png') });
  await page.getByRole('button', { name: 'Добавить объект', exact: true }).click();
  await page.getByLabel('Адрес объекта', { exact: true }).fill('Учебный объект, Строительная улица, 12');
  await page.getByRole('button', { name: 'Создать карточку', exact: true }).click();
  await page.getByText('Учебный объект, Строительная улица, 12', { exact: true }).waitFor();
  await page.getByText('Учебный объект, Строительная улица, 12', { exact: true }).click();
  await page.getByRole('button', { name: 'Редактировать', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Редактировать', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Редактировать', exact: true }).click();
  await page.getByLabel('Адрес объекта', { exact: true }).fill('Учебный объект, Строительная улица, 14');
  await page.getByRole('button', { name: 'Сохранить изменения', exact: true }).click();
  await page.getByText('Учебный объект, Строительная улица, 14', { exact: true }).waitFor();
  await page.getByRole('button', { name: '← К списку', exact: true }).click();
  await page.getByRole('button', { name: 'Меню', exact: true }).click();
  await page.getByRole('button', { name: 'Сотрудники', exact: true }).click();
  await page.getByRole('button', { name: 'Добавить сотрудника', exact: true }).click();
  await page.getByLabel('ФИО', { exact: true }).fill('Тестов Тест Тестович');
  await page.getByLabel('Личный email', { exact: true }).fill('testov@example.test');
  await page.getByLabel('Телефон', { exact: true }).fill('+7 900 123-45-67');
  await page.getByLabel('Дата рождения', { exact: true }).fill('1990-04-21');
  await page.getByLabel('Размер одежды', { exact: true }).selectOption('52');
  await page.getByLabel('Размер обуви', { exact: true }).selectOption('43');
  await page.getByLabel('Подтверждение ознакомления с политикой зафиксировано', { exact: true }).check();
  await page.screenshot({ path: join(out, 'work-02-employee-form-390.png') });
  await page.getByRole('button', { name: 'Создать карточку', exact: true }).click();
  await page.getByText('Тестов Тест Тестович', { exact: true }).waitFor();
  assert.equal(await fit(page), true, 'Горизонтальная прокрутка после создания карточки');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.screenshot({ path: join(out, 'work-03-employees-1280.png') });
  assert.equal(await fit(page), true, 'Горизонтальная прокрутка в широком кабинете');
  assert.deepEqual(errors, []);
  await context.close();
  console.log('PASS work: вход руководителя, объекты, сотрудники, мобильное меню, 390/1280 px');
} finally {
  if (browser) await browser.close();
  await app.close();
}
